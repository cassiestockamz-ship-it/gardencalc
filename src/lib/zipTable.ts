/**
 * Paint-level lookup from a partial ZIP. Returns whatever we can infer
 * from the first 1-5 digits. The result is intentionally lossy — the
 * ZIP Ring Decoder calls this on every keystroke and the /api/zone
 * endpoint provides the authoritative final value.
 */
export function lookupZipPrefix(partial: string): ZipPrefixInfo | null {
  if (partial.length < 3) return null;
  const prefix = partial.slice(0, 3);
  return PREFIX_TABLE[prefix] ?? null;
}

/**
 * Check whether a ZIP prefix is in the known table. Used to short-circuit
 * the decoder when the user has typed enough digits but the prefix is
 * not in our table (rare, mostly PO-box / military prefixes).
 */
export function isKnownPrefix(partial: string): boolean {
  if (partial.length < 3) return false;
  return PREFIX_TABLE[partial.slice(0, 3)] !== undefined;
}
